/**
 * Russian names for the stamp library, keyed by asset id.
 *
 * Separate from `ru.ts` because this is content, not interface: six hundred
 * odd entries that grow every time someone draws a new stamp, and a reviewer
 * checking a shelf's wording wants it all in one place rather than buried
 * under the toolbar strings.
 *
 * Sections follow the panel — group, then shelf — and ids are sorted inside
 * each one, so a new stamp lands in an obvious place and a diff stays local.
 * Register is held per shelf on purpose: every bunk in the prison and the
 * barracks is a «койка», every rack a «полка», so a shelf reads as one set.
 *
 * Names are captions under a 64-pixel thumbnail, so two words is the target.
 * Where English carries a "(top-down)" tag only to separate a plan view from
 * an elevation, Russian gets there through the word itself — «крона» for a
 * canopy, «сухостой» for standing deadwood — and the tag is dropped. It is
 * kept in Battle Props, where the group has no shelf to say it.
 *
 * Coverage is enforced by `node tools/check-asset-ru.mjs`.
 */

